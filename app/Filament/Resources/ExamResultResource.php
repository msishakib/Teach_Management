<?php

namespace App\Filament\Resources;

use App\Enums\ExamResultStatus;
use App\Filament\Concerns\HasStandardTable;
use App\Filament\Resources\ExamResultResource\Pages;
use App\Models\Exam;
use App\Models\ExamResult;
use Filament\Forms;
use Filament\Forms\Form;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;
use Illuminate\Database\Eloquent\Builder;

class ExamResultResource extends Resource
{
    use HasStandardTable;

    protected static ?string $model = ExamResult::class;

    protected static ?string $navigationIcon = 'heroicon-o-chart-bar-square';

    protected static ?string $navigationGroup = 'Academics';

    protected static ?int $navigationSort = 10;

    protected static ?string $modelLabel = 'Exam result';

    public static function form(Form $form): Form
    {
        return $form->schema([
            Forms\Components\Placeholder::make('info')
                ->content('Results are generated by Process results on the Exam edit page.'),
        ]);
    }

    public static function table(Table $table): Table
    {
        return static::configureStandardTable($table)
            ->columns([
                Tables\Columns\TextColumn::make('exam.name')
                    ->searchable()
                    ->sortable(),
                Tables\Columns\TextColumn::make('student.admission_no')
                    ->label('Admission no')
                    ->searchable()
                    ->sortable(),
                Tables\Columns\TextColumn::make('student.name')
                    ->searchable()
                    ->sortable(),
                Tables\Columns\TextColumn::make('total_marks')
                    ->sortable(),
                Tables\Columns\TextColumn::make('percentage')
                    ->sortable(),
                Tables\Columns\TextColumn::make('gpa')
                    ->sortable(),
                Tables\Columns\TextColumn::make('letter_grade')
                    ->badge(),
                Tables\Columns\TextColumn::make('status')
                    ->badge()
                    ->sortable(),
                Tables\Columns\TextColumn::make('rank_in_batch')
                    ->label('Rank')
                    ->sortable(),
                Tables\Columns\TextColumn::make('published_at')
                    ->dateTime()
                    ->placeholder('Unpublished')
                    ->sortable(),
            ])
            ->filters([
                Tables\Filters\SelectFilter::make('exam_id')
                    ->label('Exam')
                    ->options(fn () => Exam::query()->orderByDesc('id')->pluck('name', 'id')),
                Tables\Filters\SelectFilter::make('status')
                    ->options(ExamResultStatus::class),
                Tables\Filters\TernaryFilter::make('published_at')
                    ->label('Published')
                    ->nullable()
                    ->trueLabel('Published')
                    ->falseLabel('Unpublished')
                    ->queries(
                        true: fn (Builder $query) => $query->whereNotNull('published_at'),
                        false: fn (Builder $query) => $query->whereNull('published_at'),
                    ),
            ])
            ->actions([
                Tables\Actions\Action::make('marksheet')
                    ->label('Marksheet')
                    ->icon('heroicon-o-printer')
                    ->url(fn (ExamResult $record) => route('exam-results.marksheet.pdf', $record))
                    ->openUrlInNewTab(),
                Tables\Actions\Action::make('certificate')
                    ->label('Certificate PDF')
                    ->icon('heroicon-o-academic-cap')
                    ->url(function (ExamResult $record) {
                        $certificate = \App\Models\Certificate::query()
                            ->where('student_id', $record->student_id)
                            ->where('exam_id', $record->exam_id)
                            ->first();

                        return $certificate ? route('certificates.pdf', $certificate) : null;
                    })
                    ->visible(fn (ExamResult $record) => \App\Models\Certificate::query()
                        ->where('student_id', $record->student_id)
                        ->where('exam_id', $record->exam_id)
                        ->exists())
                    ->openUrlInNewTab(),
            ]);
    }

    public static function getEloquentQuery(): Builder
    {
        return parent::getEloquentQuery()
            ->withoutGlobalScopes()
            ->with(['exam', 'student']);
    }

    public static function canCreate(): bool
    {
        return false;
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListExamResults::route('/'),
        ];
    }
}
